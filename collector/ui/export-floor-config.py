#!/usr/bin/env python3
"""Export only reviewed room outlines and receiver anchors from the HA model."""

import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
from scripts.site_context import (  # noqa: E402
    load_pinned_json,
    load_site_context,
    write_private_output,
)

MAX_MODEL_BYTES = 64 * 1024 * 1024


def interp(value, anchors):
    a, b = anchors[:2]
    for index in range(len(anchors) - 1):
        a, b = anchors[index : index + 2]
        if value <= b[0]:
            break
    return a[1] + (value - a[0]) * (b[1] - a[1]) / (b[0] - a[0])


def render(model, model_bytes, profile, context, source_revision):
    activity = context.documents["assumed-activity.json"]
    placements = context.documents["placements.json"]
    if set(profile) != {"model_id", "floor", "zone_labels"}:
        raise ValueError("Expected an approved UI export profile")
    if model["id"] != profile["model_id"] or placements["floor"] != profile["floor"]:
        raise ValueError("Model and floor differ from the approved export profile")
    if not isinstance(profile["zone_labels"], dict) or any(
        not isinstance(key, str) or not isinstance(value, str)
        for key, value in profile["zone_labels"].items()
    ):
        raise ValueError("UI export zone labels must be strings")
    if not re.fullmatch("[a-f0-9]{40}", source_revision):
        raise ValueError("An exact model source revision is required")
    calibration = model["calibration"]

    def point(x, z):
        return [
            interp(x, calibration["x_anchors"]),
            interp(z, calibration["z_anchors"]),
        ]

    rooms = [
        {
            "id": room["id"],
            "display_id": model["room_display_ids"].get(room["id"], room["id"]),
            "name": model["room_display_names"].get(room["id"], room["name"]),
            "polygon": [point(*p) for p in room["polygon"]],
            "label": point(*room["label"]),
        }
        for room in model["rooms"]
    ]
    names = profile["zone_labels"]
    anchors = {row["node_id"]: row["position_xz_m"] for row in activity["receivers"]}
    receivers = []
    for node_id, item in enumerate(placements["items"], 1):
        if item["entity_id"] != f"binary_sensor.ruview_node{node_id}_presence":
            raise ValueError("Receiver identity/order changed; review before export")
        position = item["position_m"]
        if [position["x"], position["z"]] != anchors[node_id]:
            raise ValueError("Activity and placement anchors disagree")
        receivers.append(
            {
                "node_id": node_id,
                "name": item["name"].replace("RuView — ", ""),
                "room_id": item["room"],
                "position": anchors[node_id],
                "height_m": position["y"] + item["dimensions_m"]["height"] / 2,
            }
        )
    result = {
        "schema": "ruview.home-floor.ui.v1",
        "source_revision": source_revision,
        "model_sha256": hashlib.sha256(model_bytes).hexdigest(),
        "coordinate_frame": activity["coordinate_frame"],
        "geometry_assumed": True,
        "rooms": rooms,
        "receivers": receivers,
        "zones": [
            {
                "id": z["zone_id"],
                "name": names[z["zone_id"]],
                "room_id": z["room_id"],
                "polygon": z["polygon_xz_m"],
            }
            for z in activity["zones"]
        ],
    }
    return (
        "// Generated by export-floor-config.py; no credentials or HA inventory.\n"
        + "export const FLOOR = "
        + json.dumps(result, indent=2, ensure_ascii=False)
        + ";\n"
    ).encode("utf-8")


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("model", type=Path)
    parser.add_argument("--model-sha256", required=True)
    parser.add_argument("--profile", type=Path, required=True)
    parser.add_argument("--profile-sha256", required=True)
    parser.add_argument("--site-context", type=Path, required=True)
    parser.add_argument("--site-context-sha256", required=True)
    parser.add_argument("--source-revision", required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args(argv)
    context = load_site_context(args.site_context, args.site_context_sha256)
    model_bytes, model = load_pinned_json(
        args.model, args.model_sha256, MAX_MODEL_BYTES
    )
    _, profile = load_pinned_json(args.profile, args.profile_sha256)
    raw = render(model, model_bytes, profile, context, args.source_revision)
    # Check all approvals again before publishing the complete private result.
    load_site_context(args.site_context, args.site_context_sha256)
    load_pinned_json(args.model, args.model_sha256, MAX_MODEL_BYTES)
    load_pinned_json(args.profile, args.profile_sha256)
    write_private_output(args.output, raw)


if __name__ == "__main__":
    main()
